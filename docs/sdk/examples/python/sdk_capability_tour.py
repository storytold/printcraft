#!/usr/bin/env python3
"""PdfCraft SDK Capability Tour: a 5-page generated showcase PDF.

# Architecture Reference
Script: docs/sdk/examples/python/sdk_capability_tour.py
Purpose:
    Builds a visually rich PDF entirely through the public PdfCraft Python SDK
    (`DocumentSession`, `Style`, `StyleTransition`, `Color`, `Rect`,
    `DocTextFinderConfig`). Every number printed in the document is computed by
    the script at build time, so the PDF documents its own construction.

      Page 1  Cover: generated interference-pattern hero image, stat tiles.
      Page 2  Typography: font families, StyleTransition runs, word-wrapped
              text boxes, and a 24-colour palette heat strip.
      Page 3  Data: a vector bar chart, a raster Mandelbrot plate, and a table.
      Page 4  Review: find_text() hits drawn as highlights, stamps, comment
              cards, and form-field views.
      Page 5  Landscape roadmap: page-geometry control, a Gantt-style timeline (illustrative data).

Usage:
    python3 docs/sdk/examples/python/sdk_capability_tour.py
    python3 docs/sdk/examples/python/sdk_capability_tour.py \
        --output sample-docs/outputs/sdk_capability_tour.pdf --render-previews

Notes:
    * Built-in PDF fonts only encode Latin-1 here, so all text is plain ASCII.
    * `--render-previews` needs `pdftoppm` (poppler) on PATH.
"""

